"""Supplier API — export des partenaires (clients / fournisseurs) vers un format de fichier cible.

    GET  /api/exports/targets                              formats disponibles
    GET  /api/exports/{system}/{product}/profile           paramètres d'export de votre organisation
    PUT  /api/exports/{system}/{product}/profile           enregistrer (validés : format, motifs, plages)
    GET  /api/exports/{system}/{product}/preview?system_id= aperçu (lecture seule, rien n'est réservé)
    POST /api/exports/{system}/{product}/files             générer le fichier (numéros réservés, journal)
    GET  /api/exports/runs                                 fichiers générés (journal, sans contenu)

TenantContext obligatoire : profil, numéros et journal de l'organisation du contexte ; un système d'une autre
organisation est introuvable. Rien n'est envoyé au système cible : le fichier est rendu à l'utilisateur.
"""

from __future__ import annotations

import uuid

from fastapi import APIRouter, HTTPException, Response
from uie_core.exports import ExportProfileRecord
from uie_core.registry import NotFound

from uie_api.deps import TenantExportProfiles, TenantPartnerExport
from uie_api.supplier_exports import (
    ExportFileIn,
    ExportPreviewOut,
    ExportProfileIn,
    ExportProfileOut,
    ExportRunOut,
    ExportTargetOut,
    export_preview,
    export_run,
    export_target,
    profile_param,
)

router = APIRouter(prefix="/api/exports", tags=["supplier-exports"])
TARGET = "/{system}/{product}"


@router.get("/targets", summary="Formats your partners can be exported to")
def list_targets(profiles: TenantExportProfiles) -> list[ExportTargetOut]:
    out = []
    for b in profiles.targets():
        try:
            target = profiles.target(b.target.system, b.target.product)
        except NotFound:
            target = None
        out.append(export_target(b, target))
    return out


def _profile_out(profiles: TenantExportProfiles, system: str, product: str, row: ExportProfileRecord | None):  # noqa: ANN202
    target = profiles.target(system, product)
    values = dict(row.values) if row else {}
    complete = all(values.get(p.name) not in (None, "") for p in target.binding.profile if p.required)
    return ExportProfileOut(
        target=export_target(target.binding, target),
        params=[profile_param(p) for p in target.binding.profile],
        values=values,
        complete=bool(row) and complete,
        updated_at=row.updated_at if row else None,
    )


@router.get(TARGET + "/profile", summary="Your export settings for this format")
def get_profile(profiles: TenantExportProfiles, system: str, product: str) -> ExportProfileOut:
    return _profile_out(profiles, system, product, profiles.get(system, product))


@router.put(
    TARGET + "/profile",
    summary="Save your export settings (checked against the format)",
    responses={422: {"description": "Invalid settings: one message per setting"}},
)
def save_profile(
    profiles: TenantExportProfiles, system: str, product: str, body: ExportProfileIn
) -> ExportProfileOut:
    row = profiles.save(system, product, body.values)
    return _profile_out(profiles, system, product, row)


@router.get(TARGET + "/preview", summary="Preview the export of a system's partners (nothing is reserved)")
def preview(
    exports: TenantPartnerExport, system: str, product: str, system_id: uuid.UUID
) -> ExportPreviewOut:
    result = exports.preview(system, product, system_id)
    return export_preview(result, exports.profiles.target(system, product))


@router.post(
    TARGET + "/files",
    summary="Generate the export file (account numbers are reserved; the file is not sent anywhere)",
    response_class=Response,
    responses={200: {"content": {"text/csv": {}}, "description": "The export file"}},
)
def generate(exports: TenantPartnerExport, system: str, product: str, body: ExportFileIn) -> Response:
    try:
        instance_id = uuid.UUID(body.system_id)
    except ValueError:
        raise HTTPException(404, "System not found") from None
    file = exports.generate(system, product, instance_id)
    return Response(
        content=file.content,
        media_type=file.media_type,
        headers={
            "Content-Disposition": f'attachment; filename="{file.filename}"',
            "X-Export-Run": str(file.run.id),
        },
    )


@router.get("/runs", summary="Export files generated by your organization (no content kept)")
def list_runs(exports: TenantPartnerExport) -> list[ExportRunOut]:
    return [export_run(run, system) for run, system in exports.runs()]
